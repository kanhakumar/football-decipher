package smi.generator

import smi.model.TeamId

/** Per-match averages over many seeds, compared with target bands (ADR-008). */
object Calibration:
  /** A target band. `value` reduces all matches to one number (usually a per-match average). */
  final case class Metric(
      name: String,
      lo: Double,
      hi: Double,
      value: Vector[MatchSummary] => Double,
      percent: Boolean = false
  )

  final case class Result(metric: Metric, value: Double):
    def inRange: Boolean = value >= metric.lo && value <= metric.hi
    private def fmt(v: Double) =
      if metric.percent then f"${v * 100}%.1f%%" else f"$v%.2f"
    def valueText: String = fmt(value)
    def bandText: String = s"${fmt(metric.lo)} to ${fmt(metric.hi)}"

  private def avg(f: MatchSummary => Double)(ms: Vector[MatchSummary]) = ms.map(f).sum / ms.size

  private val home: TeamId = Squads.home.teamId
  private val away: TeamId = Squads.away.teamId

  val metrics: Vector[Metric] = Vector(
    Metric("goals per match", 2.5, 3.0, avg(_.totalGoals)),
    Metric("shots per match", 20, 28, avg(_.totalShots)),
    Metric("shots on target per match", 7, 10, avg(_.shotsOnTarget)),
    Metric("passes per team (home)", 350, 550, avg(_.passes.getOrElse(home, 0).toDouble)),
    Metric("passes per team (away)", 350, 550, avg(_.passes.getOrElse(away, 0).toDouble)),
    Metric("pass completion", 0.78, 0.90, avg(_.passCompletion), percent = true),
    Metric("home possession, average", 0.45, 0.55, avg(_.possessionShare(home)), percent = true),
    Metric(
      "home possession, lowest match",
      0.35,
      0.65,
      _.map(_.possessionShare(home)).min,
      percent = true
    ),
    Metric(
      "home possession, highest match",
      0.35,
      0.65,
      _.map(_.possessionShare(home)).max,
      percent = true
    ),
    Metric("fouls per match", 18, 26, avg(_.fouls)),
    Metric("events per match", 1500, 2500, avg(_.events))
  )

  /** Reported for context, not gated. */
  val context: Vector[(String, Vector[MatchSummary] => Double)] = Vector(
    "yellow cards per match" -> avg(_.yellowCards),
    "red cards per match" -> avg(_.redCards.size),
    "penalty goals per match" -> avg(
      _.goals.count(_.situation.contains(smi.model.ShotSituation.Penalty))
    ),
    "match clock, minutes" -> avg(_.durationMinutes)
  )

  val DefaultSeeds = 200

  /** The scenario's styles and phases without its story beats: what the model does unscripted. */
  def baseline(s: Scenario): Scenario = s.copy(name = s"${s.name} without beats", beats = None)

  def summaries(seeds: Seq[Long], scenario: Scenario): Vector[MatchSummary] =
    seeds.toVector.map(s => MatchSummary.of(MatchGenerator.generate(GeneratorConfig(s, scenario))))

  def evaluate(ms: Vector[MatchSummary]): Vector[Result] = metrics.map(m => Result(m, m.value(ms)))

  /** Gated baseline and reported story scenario, measured on the same seeds. */
  final case class Run(
      seeds: Int,
      scenario: Scenario,
      base: Vector[MatchSummary],
      story: Vector[MatchSummary]
  ):
    val baseResults: Vector[Result] = evaluate(base)
    val storyResults: Vector[Result] = evaluate(story)
    def outOfRange: Int = baseResults.count(!_.inRange)

  def run(seeds: Int, scenario: Scenario): Run =
    val range = 1L to seeds.toLong
    Run(seeds, scenario, summaries(range, baseline(scenario)), summaries(range, scenario))

  def table(r: Run): String =
    val width = (metrics.map(_.name) ++ context.map(_._1)).map(_.length).max
    val header =
      s"     ${"metric".padTo(width, ' ')}  ${"baseline".padTo(9, ' ')}  ${"story".padTo(9, ' ')}  target"
    val rows = r.baseResults.zip(r.storyResults).map { (b, st) =>
      val mark = if b.inRange then "ok " else "OUT"
      s"$mark  ${b.metric.name.padTo(width, ' ')}  ${b.valueText.padTo(9, ' ')}  ${st.valueText.padTo(9, ' ')}  ${b.bandText}"
    }
    val extra =
      context.map((n, f) => f"     ${n.padTo(width, ' ')}  ${f(r.base)}%-9.2f  ${f(r.story)}%-9.2f")
    (header +: (rows ++ extra)).mkString("\n")

  def markdown(r: Run): String =
    val gated = r.baseResults.zip(r.storyResults).map { (b, st) =>
      val status = if b.inRange then "in range" else "OUT"
      s"| ${b.metric.name} | ${b.valueText} | ${st.valueText} | ${b.bandText} | $status |"
    }
    val extra = context.map((n, f) => f"| $n | ${f(r.base)}%.2f | ${f(r.story)}%.2f |")
    val lines =
      Vector(
        "# Generator calibration",
        "",
        s"Generated by `sbt \"calibrate --report ../docs/calibration.md\"`: ${r.seeds} seeds (1 to ${r.seeds}), scenario `${r.scenario.name}`.",
        "",
        "The **baseline** is the scenario's team styles and tactical phase without its story beats, so it shows what the model does unscripted. It is the gate: every metric must be in range. The **story** column is the full scenario (the demo match). Its scripted counter-attack goal and red card add about one goal and one red card per match by design, so it is reported, not gated. Targets are the project brief's realism bands (ADR-008); the bands for shots on target, passes per team and fouls are plausibility bands chosen for this project (ADR-008).",
        "",
        "| Metric | Baseline | Story | Target | Baseline status |",
        "|---|---|---|---|---|"
      ) ++ gated ++
        Vector(
          "",
          "Context (not gated):",
          "",
          "| Metric | Baseline | Story |",
          "|---|---|---|"
        ) ++ extra ++
        Vector(
          "",
          "Possession is the share of passes. Shots on target are goals plus saves (the woodwork counts as off target)."
        )
    lines.mkString("", "\n", "\n")
